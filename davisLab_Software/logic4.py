def analyze_results(base_dir, residues=None):
    """
    THIS IS THE FUNCTION CALLED BY gui.py
    Returns (pivot_delta, pivot_annot, summary_df, error_msg).
    CHANGED: reads ONLY the saved OSPREY stdout in each residue folder (no TSV fallback).

    residues : optional collection of residue keys (e.g. {"A38S", "A41Q"}). When given,
               only results from those residue folders are included, so leftover output
               from earlier sessions doesn't show up.
    """
    folders = get_residue_folders(base_dir, residues)
    if not folders:
        return None, None, None, "No residue result folders found in output directory."

    all_rows, errors = [], []
    for folder in folders:
        try:
            all_rows.extend(read_stdout_data(folder))
        except StdoutParseError as e:
            errors.append(str(e))

    if errors:
        return None, None, None, "\n".join(errors)

    master_df = pd.DataFrame(all_rows)

    # Heatmap matrix. Do NOT fillna(0): a missing cell means "never tested", which is
    # different from a tested mutation with an exact 0.000 delta. gui.py's heatmap and
    # logic6.select_best_mutations() both rely on NaN to tell the two apart.
    pivot_delta = master_df.pivot_table(
        index=['WT_Full'],
        columns='Mutation',
        values='Delta',
        aggfunc='first'
    ).sort_index()

    # Annotation matrix: same shape as pivot_delta, mutation code in each occupied cell
    presence = master_df.pivot_table(
        index=['WT_Full'],
        columns='Mutation',
        values='Delta',
        aggfunc='count'
    ).reindex(index=pivot_delta.index, columns=pivot_delta.columns)
    pivot_annot = presence.apply(
        lambda col: col.apply(lambda n: col.name if pd.notna(n) and n > 0 else '')
    )

    # Summary table: mutation name + score as a readable string per residue site
    summary_df = master_df.copy()
    summary_df['Label'] = summary_df['Mutation'] + " (" + summary_df['Score'].astype(str) + ")"
    mutation_summary = summary_df.groupby(['WT_Full'])['Label'].apply(lambda x: ', '.join(x)).reset_index()
    mutation_summary.rename(columns={'WT_Full': 'Residue Site', 'Label': 'Mutations & Log10 Scores'}, inplace=True)

    return pivot_delta, pivot_annot, mutation_summary, None