import os
import re
import glob
import pandas as pd
import io

SCORE_COLS = ['K* Lower (log10)', 'K* Score (Log10)', 'K* Score (log10)']

# ── CHANGED: new constants for reading saved OSPREY stdout ───────────────────
STDOUT_FILENAME = "osprey_stdout.txt"

STDOUT_PATTERN = re.compile(
    r"sequence\s+\d+/\s+\d+\s+([A-Za-z0-9_=]+)\s+K\*\([^\)]*\):\s*([\d\.\-]+)"
)

AA_1TO3 = {
    'A': 'ALA', 'R': 'ARG', 'N': 'ASN', 'D': 'ASP', 'C': 'CYS',
    'Q': 'GLN', 'E': 'GLU', 'G': 'GLY', 'H': 'HIS', 'I': 'ILE',
    'L': 'LEU', 'K': 'LYS', 'M': 'MET', 'F': 'PHE', 'P': 'PRO',
    'S': 'SER', 'T': 'THR', 'W': 'TRP', 'Y': 'TYR', 'V': 'VAL',
}


class StdoutParseError(Exception):
    """Raised when a residue's saved OSPREY stdout is missing or unreadable."""
# ─────────────────────────────────────────────────────────────────────────────


def get_tsv_files_paths(base_dir):
    """Finds all OSPREY results files in the directory tree."""
    tsv_files = []
    for root, _, files in os.walk(base_dir):
        for file in files:
            # Look for the specific result files generated by OSPREY
            if file.endswith('.tsv') and 'bbkstar_results' in file:
                tsv_files.append(os.path.join(root, file))
    return tsv_files


def extract_unique_name_fragments(tsv_file, unique_name_fragments_set):
    """Extracts the 'fragment' part of the filename (e.g., 'out')."""
    basename = os.path.basename(tsv_file)
    name_no_ext = os.path.splitext(basename)[0]
    parts = name_no_ext.split('_')

    # Logic: bbkstar_results_{fragment}_{residue}
    if len(parts) >= 4:
        fragment = "_".join(parts[2:-1])
        unique_name_fragments_set.add(fragment)
        return fragment
    return None


def _parse_tsv(tsv_file):
    """
    Parses an OSPREY BBK* results TSV.

    OSPREY writes the wild-type sequence as its own row (Seq ID -1) on the line
    ABOVE the header, followed by the header and then the mutant rows. Returns
    (wt_name, wt_score, df_of_rows_below_header, score_col) or None if unreadable.
    """
    with open(tsv_file, 'r') as f:
        lines = [ln for ln in f.read().splitlines() if ln.strip()]

    header_idx = next((i for i, ln in enumerate(lines) if 'Sequence' in ln and 'K*' in ln), -1)
    if header_idx == -1:
        return None

    header = lines[header_idx].split('\t')
    score_col = next((c for c in SCORE_COLS if c in header), None)
    if score_col is None or 'Sequence' not in header:
        return None
    seq_i, score_i = header.index('Sequence'), header.index(score_col)

    # Wild-type row = the line(s) above the header
    wt_name, wt_score = None, None
    for ln in lines[:header_idx]:
        cells = ln.split('\t')
        if len(cells) > max(seq_i, score_i) and '=' in cells[seq_i]:
            wt_name, wt_score = cells[seq_i], float(cells[score_i])
            break

    df = pd.read_csv(io.StringIO("\n".join(lines[header_idx:])), sep='\t')
    return wt_name, wt_score, df, score_col


def read_file_data(tsv_file):
    """Returns a list of dicts (WT_Full, Mutation, Score, Delta) for one residue's TSV.
    Deltas are measured against the true wild-type row (Seq ID -1)."""
    try:
        parsed = _parse_tsv(tsv_file)
        if parsed is None:
            return None
        wt_name, wt_score, df, score_col = parsed

        # Run produced no mutant rows (crashed / not finished) -> nothing to show
        if wt_name is None or len(df) == 0:
            return None

        wt_full_name = wt_name.upper()          # e.g. "A38=SER"

        # Wild type first, then every scored sequence; first occurrence of an AA wins
        entries = [(wt_name, wt_score)] + [(str(r['Sequence']), float(r[score_col])) for _, r in df.iterrows()]
        seen, results = set(), []
        for seq, score in entries:
            mut_aa = seq.split('=')[-1].upper()
            if mut_aa in seen:
                continue
            seen.add(mut_aa)
            results.append({
                'WT_Full': wt_full_name,
                'Mutation': mut_aa,
                'Score': round(score, 3),
                'Delta': round(score - wt_score, 3),
            })
        return results
    except Exception as e:
        print(f"Error parsing {tsv_file}: {e}")
        return None


def _expected_sequence_count(folder):
    """Number of sequences the residue's OSPREY script asked for (library AAs + wild type)."""
    for script in glob.glob(os.path.join(folder, 'bbkstar_out_*.py')):
        with open(script, 'r') as f:
            for line in f:
                m = re.search(r"setLibraryRotamers\(osprey\.WILD_TYPE,((?:\s*'[A-Za-z]{3}',?)+)\)", line)
                if m:
                    return len(re.findall(r"'[A-Za-z]{3}'", m.group(1))) + 1
    return None


def check_run_completeness(base_dir, residues=None):
    """
    Returns a list of human-readable warnings for residues whose TSV has no results
    or fewer sequences than the script requested (crashed / interrupted runs).
    """
    warnings = []
    paths = get_tsv_files_paths(base_dir)
    if residues is not None:
        wanted = set(residues)
        paths = [p for p in paths if os.path.basename(os.path.dirname(p)) in wanted]
    for path in sorted(paths):
        folder = os.path.dirname(path)
        res = os.path.basename(folder)
        try:
            parsed = _parse_tsv(path)
        except Exception:
            parsed = None
        n = 0 if parsed is None else len(parsed[2])
        expected = _expected_sequence_count(folder)
        if n == 0:
            warnings.append(f"{res}: no mutation scores in the results file — the run did not finish, so it is excluded.")
        elif expected and n < expected:
            warnings.append(f"{res}: only {n} of {expected} expected sequences were scored — run looks incomplete.")
    return warnings


# ── CHANGED: new functions that read the saved stdout ────────────────────────
def get_residue_folders(base_dir, residues=None):
    """Finds residue folders (the ones containing a bbkstar_results TSV or a saved stdout file)."""
    folders = set()
    for root, _, files in os.walk(base_dir):
        if STDOUT_FILENAME in files or any(
            f.endswith(".tsv") and "bbkstar_results" in f for f in files
        ):
            folders.add(root)
    if residues is not None:
        wanted = set(residues)
        folders = {f for f in folders if os.path.basename(f) in wanted}
    return sorted(folders)


def read_stdout_data(folder):
    """
    Parses <folder>/osprey_stdout.txt.
    The wild-type line is found by amino-acid name (from the folder name, e.g. A38S -> SER),
    not by position. Raises StdoutParseError (never falls back to the TSV).
    """
    residue = os.path.basename(folder)
    stdout_path = os.path.join(folder, STDOUT_FILENAME)

    if not os.path.exists(stdout_path):
        raise StdoutParseError(
            f"{residue}: no saved OSPREY stdout found at '{stdout_path}'. "
            f"The run either did not finish or its output was not saved in Step 3."
        )

    with open(stdout_path, "r", encoding="utf-8", errors="ignore") as f:
        text = f.read()

    if not text.strip():
        raise StdoutParseError(f"{residue}: '{stdout_path}' is empty.")

    matches = STDOUT_PATTERN.findall(text)
    if not matches:
        raise StdoutParseError(
            f"{residue}: no 'sequence N/M <SEQ> K*(...): <score>' lines found in "
            f"'{stdout_path}'. The OSPREY output format may have changed or the run crashed."
        )

    # Work out the wild-type amino acid from the folder name (e.g. A38S -> SER)
    m = re.fullmatch(r"([A-Za-z])(\d+)([A-Za-z])", residue)
    if not m:
        raise StdoutParseError(
            f"{residue}: folder name is not like 'A38S', so the wild-type amino acid cannot be determined."
        )
    wt_aa = AA_1TO3.get(m.group(3).upper())
    if wt_aa is None:
        raise StdoutParseError(f"{residue}: '{m.group(3)}' is not a standard amino acid letter.")

    # Find the line for the wild-type amino acid, wherever it appears
    wt_entry = next(
        ((seq, sc) for seq, sc in matches if seq.split("=")[-1].upper() == wt_aa),
        None,
    )
    if wt_entry is None:
        raise StdoutParseError(
            f"{residue}: no wild-type line ({wt_aa}) found in '{stdout_path}', "
            f"so ΔK* cannot be calculated."
        )

    wt_seq, wt_score_str = wt_entry
    wt_score = float(wt_score_str)
    wt_full = f"{wt_seq.split('=')[0]}={wt_aa}"

    seen, results = set(), []
    for seq, score_str in matches:
        mut_aa = seq.split("=")[-1].upper()
        if mut_aa in seen:
            continue
        seen.add(mut_aa)
        score = float(score_str)
        results.append({
            "WT_Full": wt_full,
            "Mutation": mut_aa,
            "Score": round(score, 3),
            "Delta": round(score - wt_score, 3),
        })
    return results
